#!/bin/bash
# Zoraxy HA (keepalived) integration installer (custom fork). Run once per
# node as root, after reviewing these files:
#   sudo bash install.sh
#
# Installs (all root-owned, not writable by Zoraxy):
#   /usr/local/sbin/zoraxy-ha-apply          builds keepalived.conf from Zoraxy's settings
#   /usr/local/lib/zoraxy-ha/check           keepalived health check (runs as the zoraxy user)
#   /usr/local/lib/zoraxy-ha/notify          keepalived role notification (runs as the zoraxy user)
#   /etc/systemd/system/zoraxy-ha-apply.path and .service
# Creates:
#   /var/lib/zoraxy/ha    owned by the zoraxy user: settings, heartbeat, role
#   /var/lib/zoraxy-ha    root-owned, readable by the zoraxy group: apply results
#
# Set ZORAXY_USER if Zoraxy runs as a user other than "zoraxy".
set -euo pipefail
cd "$(dirname "$0")"
ZUSER="${ZORAXY_USER:-zoraxy}"

[ "$(id -u)" = "0" ] || { echo "Run as root: sudo bash $0" >&2; exit 1; }
id "$ZUSER" >/dev/null 2>&1 || { echo "User $ZUSER does not exist (set ZORAXY_USER)" >&2; exit 1; }
command -v keepalived >/dev/null || { echo "keepalived is not installed: apt install keepalived" >&2; exit 1; }
command -v systemctl >/dev/null || { echo "systemd is required" >&2; exit 1; }
ZGROUP="$(id -gn "$ZUSER")"

for f in zoraxy-ha-apply check notify zoraxy-ha-apply.path zoraxy-ha-apply.service; do
	[ -f "$f" ] || { echo "Missing $f next to install.sh" >&2; exit 1; }
done

install -d -o root -g root -m 0755 /usr/local/lib/zoraxy-ha
install -o root -g root -m 0755 check notify /usr/local/lib/zoraxy-ha/
install -o root -g root -m 0755 zoraxy-ha-apply /usr/local/sbin/zoraxy-ha-apply
sed -i "s/^OWNER=\"\${HA_OWNER:-zoraxy}\"/OWNER=\"\${HA_OWNER:-$ZUSER}\"/" /usr/local/sbin/zoraxy-ha-apply

install -d -o "$ZUSER" -g "$ZGROUP" -m 0750 /var/lib/zoraxy/ha
install -d -o root -g "$ZGROUP" -m 0750 /var/lib/zoraxy-ha
install -d -o root -g root -m 0755 /etc/keepalived

if [ -f /etc/keepalived/keepalived.conf ] && ! head -n1 /etc/keepalived/keepalived.conf | grep -q '^# Generated by zoraxy-ha-apply'; then
	cp -p /etc/keepalived/keepalived.conf /etc/keepalived/keepalived.conf.pre-zoraxy
	echo "Existing keepalived.conf saved as /etc/keepalived/keepalived.conf.pre-zoraxy"
fi

install -o root -g root -m 0644 zoraxy-ha-apply.path zoraxy-ha-apply.service /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now zoraxy-ha-apply.path
systemctl enable keepalived

# Apply settings Zoraxy may already have saved
if [ -f /var/lib/zoraxy/ha/cluster.env ]; then
	systemctl start zoraxy-ha-apply.service || true
fi

echo
echo "Zoraxy HA integration installed. Next: open Zoraxy > Networking > High Availability,"
echo "enter the cluster settings and save. Repeat this install on the other node."
