#!/bin/bash
# Waymark Proxy HA (keepalived) integration installer. Run once per
# node as root, after reviewing these files:
#   sudo bash install.sh
#
# Installs (all root-owned, not writable by Waymark):
#   /usr/local/sbin/waymark-ha-apply          builds keepalived.conf from Waymark's settings
#   /usr/local/lib/waymark-ha/check           keepalived health check (runs as the waymark user)
#   /usr/local/lib/waymark-ha/notify          keepalived role notification (runs as the waymark user)
#   /etc/systemd/system/waymark-ha-apply.path and .service
# Creates:
#   /var/lib/waymark/ha    owned by the waymark user: settings, heartbeat, role
#   /var/lib/waymark-ha    root-owned, readable by the waymark group: apply results
#
# If Waymark's systemd service is sandboxed (ProtectSystem=strict), adds a
# drop-in letting it write /var/lib/waymark/ha; restart Waymark afterwards.
# keepalived is enabled and started by waymark-ha-apply when HA is turned on
# in Waymark, and stopped and disabled when it is turned off.
#
# Set WAYMARK_USER if Waymark runs as a user other than "waymark", and
# WAYMARK_UNIT if its service can't be found automatically.
set -euo pipefail
cd "$(dirname "$0")"
ZUSER="${WAYMARK_USER:-waymark}"

[ "$(id -u)" = "0" ] || { echo "Run as root: sudo bash $0" >&2; exit 1; }
id "$ZUSER" >/dev/null 2>&1 || { echo "User $ZUSER does not exist (set WAYMARK_USER)" >&2; exit 1; }
command -v keepalived >/dev/null || { echo "keepalived is not installed: apt install keepalived" >&2; exit 1; }
command -v systemctl >/dev/null || { echo "systemd is required" >&2; exit 1; }
ZGROUP="$(id -gn "$ZUSER")"

for f in waymark-ha-apply check notify waymark-ha-apply.path waymark-ha-apply.service; do
	[ -f "$f" ] || { echo "Missing $f next to install.sh" >&2; exit 1; }
done

install -d -o root -g root -m 0755 /usr/local/lib/waymark-ha
install -o root -g root -m 0755 check notify /usr/local/lib/waymark-ha/
install -o root -g root -m 0755 waymark-ha-apply /usr/local/sbin/waymark-ha-apply
sed -i "s/^OWNER=\"\${HA_OWNER:-waymark}\"/OWNER=\"\${HA_OWNER:-$ZUSER}\"/" /usr/local/sbin/waymark-ha-apply

install -d -o "$ZUSER" -g "$ZGROUP" -m 0750 /var/lib/waymark/ha
install -d -o root -g "$ZGROUP" -m 0750 /var/lib/waymark-ha
install -d -o root -g root -m 0755 /etc/keepalived

# Upgrading from the Zoraxy-based builds (3.3.5-custom.N): remove their HA
# integration (zoraxy-ha-apply). keepalived keeps its current config until
# Waymark applies its settings again when it starts.
migrated=""
if [ -e /etc/systemd/system/zoraxy-ha-apply.path ] || [ -e /usr/local/sbin/zoraxy-ha-apply ] || [ -d /var/lib/zoraxy/ha ]; then
	echo "Removing the HA integration of the Zoraxy-based builds (zoraxy-ha-apply)"
	systemctl disable --now zoraxy-ha-apply.path >/dev/null 2>&1 || true
	systemctl stop zoraxy-ha-apply.service >/dev/null 2>&1 || true
	rm -f /etc/systemd/system/zoraxy-ha-apply.path /etc/systemd/system/zoraxy-ha-apply.service /usr/local/sbin/zoraxy-ha-apply
	rm -rf /usr/local/lib/zoraxy-ha
	rm -f /etc/systemd/system/*.service.d/zoraxy-ha.conf
	# Keep the record of the last configuration copy, so a standby does not copy it again
	if [ -f /var/lib/zoraxy/ha/sync-applied.json ] && [ ! -e /var/lib/waymark/ha/sync-applied.json ]; then
		install -o "$ZUSER" -g "$ZGROUP" -m 0600 /var/lib/zoraxy/ha/sync-applied.json /var/lib/waymark/ha/sync-applied.json
	fi
	rm -rf /var/lib/zoraxy/ha /var/lib/zoraxy-ha
	rmdir /var/lib/zoraxy 2>/dev/null || true
	systemctl daemon-reload
	migrated=1
fi

if [ -f /etc/keepalived/keepalived.conf ] && ! head -n1 /etc/keepalived/keepalived.conf | grep -qE '^# Generated by (waymark|zoraxy)-ha-apply'; then
	cp -p /etc/keepalived/keepalived.conf /etc/keepalived/keepalived.conf.pre-waymark
	echo "Existing keepalived.conf saved as /etc/keepalived/keepalived.conf.pre-waymark"
fi

install -o root -g root -m 0644 waymark-ha-apply.path waymark-ha-apply.service /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now waymark-ha-apply.path

# Waymark's own service: ProtectSystem=strict makes /var/lib read-only to it
restart_note=""
unit="${WAYMARK_UNIT:-}"
if [ -z "$unit" ]; then
	for pid in $(pgrep -x -u "$ZUSER" waymark 2>/dev/null); do
		unit="$(sed -n 's#^0::.*/\([^/]*\.service\)$#\1#p' "/proc/$pid/cgroup" 2>/dev/null | head -n1)"
		[ -n "$unit" ] && break
	done
fi
if [ -z "$unit" ] && systemctl cat waymark.service >/dev/null 2>&1; then
	unit=waymark.service
fi
if [ -n "$unit" ] && [ "$(systemctl show "$unit" -p ProtectSystem --value 2>/dev/null)" = strict ]; then
	rw=" $(systemctl show "$unit" -p ReadWritePaths --value) "
	if [[ "$rw" == *" /var/lib/waymark "* || "$rw" == *" /var/lib/waymark/ha "* ]]; then
		echo "$unit can already write /var/lib/waymark/ha"
	else
		install -d -m 0755 "/etc/systemd/system/$unit.d"
		printf '# Added by the Waymark HA installer: lets Waymark write its HA folder\n[Service]\nReadWritePaths=/var/lib/waymark/ha\n' >"/etc/systemd/system/$unit.d/waymark-ha.conf"
		chmod 0644 "/etc/systemd/system/$unit.d/waymark-ha.conf"
		systemctl daemon-reload
		restart_note="$unit is sandboxed (ProtectSystem=strict): added /etc/systemd/system/$unit.d/waymark-ha.conf
so it can write /var/lib/waymark/ha. Restart Waymark to apply it: sudo systemctl restart $unit"
	fi
elif [ -z "$unit" ]; then
	echo "Note: could not find Waymark's systemd service. If it uses ProtectSystem=strict, add"
	echo "ReadWritePaths=/var/lib/waymark/ha to it (or rerun with WAYMARK_UNIT=<name>.service)."
fi

# Apply settings Waymark may already have saved
if [ -f /var/lib/waymark/ha/cluster.env ]; then
	systemctl start waymark-ha-apply.service || true
fi

echo
[ -n "$restart_note" ] && { echo "$restart_note"; echo; }
if [ -n "$migrated" ]; then
	echo "Waymark HA integration installed, replacing the Zoraxy-based one. Start (or restart) Waymark:"
	echo "it applies its HA settings again at startup, which points keepalived at the new scripts."
else
	echo "Waymark HA integration installed. Next: open Waymark > Networking > High Availability,"
	echo "enter the cluster settings and save. Repeat this install on the other node."
fi
