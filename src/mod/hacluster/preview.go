package hacluster

import (
	"strconv"
	"strings"
)

// Preview renders the keepalived.conf the root helper will generate for
// node self, for display in the UI. It must stay identical to the template
// in deploy/waymark-ha-apply (checked by TestPreviewMatchesHelper).
func (c *Config) Preview(self int, owner, scriptsDir string) string {
	header := "# Generated by waymark-ha-apply from Waymark's HA settings. Do not edit:\n" +
		"# changes are overwritten the next time HA settings are saved in Waymark."
	name := "node"
	if self >= 0 && self < len(c.Nodes) {
		name = c.Nodes[self].Name
	}
	global := "global_defs {\n    router_id waymark_" + name + "\n    enable_script_security\n    script_user " + owner + "\n}\n"
	if !c.Enabled || self < 0 || self >= len(c.Nodes) {
		return header + "\n# HA is turned off in Waymark: keepalived is stopped and no floating IP is managed on this node.\n\n" + global
	}
	me := c.Nodes[self]
	var peers strings.Builder
	for i, n := range c.Nodes {
		if i != self {
			peers.WriteString("        " + n.Address + "\n")
		}
	}
	auth := ""
	if c.Password != "" {
		auth = "    authentication {\n        auth_type PASS\n        auth_pass " + c.Password + "\n    }\n"
	}
	preempt := "    nopreempt"
	if c.Preempt {
		preempt = "    preempt_delay 30"
	}
	return header + "\n\n" + global + `
vrrp_script waymark_health {
    script "` + scriptsDir + `/check"
    interval 2
    timeout 2
    fall 2
    rise 2
}

vrrp_instance WAYMARK {
    state BACKUP
    interface ` + me.Interface + `
    virtual_router_id ` + strconv.Itoa(c.RouterID) + `
    priority ` + strconv.Itoa(me.Priority) + `
    advert_int 1
` + preempt + `
    unicast_src_ip ` + me.Address + `
    unicast_peer {
` + peers.String() + `    }
` + auth + `    virtual_ipaddress {
        ` + c.VIP + "/" + strconv.Itoa(c.Prefix) + ` dev ` + me.Interface + `
    }
    track_script {
        waymark_health
    }
    notify "` + scriptsDir + `/notify"
    notify_stop "` + scriptsDir + `/notify INSTANCE WAYMARK STOP"
}
`
}
